//! 017 · 多文件工程结构
//!
//! 运行：`cargo run --example 017_module`
//!
//! ⚠️ 本讲是个**目录式 example**：`examples/017_module/` 下有一个 `main.rs`
//! 和几个子模块。Cargo 会自动把 `examples/<名字>/main.rs` 识别成名为
//! `<名字>` 的 example —— 这是**目录式**；而 `examples/<名字>.rs` 是**单文件式**。
//! 子模块文件（`score.rs` 等）**不会**被当成独立的 example。
//!
//! 新增概念
//!   目录式 example   `examples/017_module/main.rs` + 同级子模块
//!   `mod` / `use`    把功能拆进文件，`main.rs` 只负责组装
//!   可见性           每个功能只 `pub` 出**插件**，系统函数保持私有
//!
//! 使用场景
//!   功能变多以后，单文件会失控：`main.rs` 只留插件清单，逻辑各归其位
//!   同一个功能有"专属资源 + 多个系统"时，一个文件就是一个自洽的单元
//!
//! 注意：本讲与 016 **功能完全相同**，只是搬了家 —— 对比 `main.rs` 的长度
//!       就能看出这个结构的价值：它从"包含全部实现"变成"只说装了什么"

mod common;
mod enemy;
mod score;

use bevy::log::LogPlugin;
use bevy::prelude::*;

use common::GameSet;

fn main() {
    let mut app = App::new();
    app.add_plugins(LogPlugin::default());

    // ★ main 里只看得见"装了哪些插件"这件事。
    // 至于每个插件里有哪些系统、什么资源，全在各自文件里。
    app.add_plugins((score::ScorePlugin, enemy::EnemyPlugin));

    // 唯一的例外：**跨插件**的顺序约束需要集中声明 ——
    // 它不属于任何一个插件，放在 main 里最合适。
    app.configure_sets(Update, GameSet::Score.after(GameSet::Enemy));

    for frame in 1..=3 {
        println!("═══ 第 {frame} 帧 ═══");
        app.update();
    }
}

// ─────────────────────────────────────────────────────────────────────
// 实测输出（与 016 逐字相同 —— 这就是本讲要的效果）
//
//   ═══ 第 1 帧 ═══
//      [分数插件] Score = 0
//   ═══ 第 2 帧 ═══
//   ═══ 第 3 帧 ═══
//      [敌人插件] 小兵甲 抵达终点，+10 分
//      [敌人插件] 小兵乙 抵达终点，+10 分
//      [分数插件] Score = 20
//
// 同样的功能、同样的输出，但 `main.rs` 从"两百行实现"变成了"三十行声明"。
//
// 补充两点（都是 0.20 实跑）：
//   · 这份输出与 016 **逐字相同**，且各自连跑 6 次都稳定。
//   · 017 比 016 少了一个 `PluginGroup`：016 用 `GamePlugins` 把两个插件再打包成一组，
//     017 直接写 `(score::ScorePlugin, enemy::EnemyPlugin)` 元组。
//     两者都能被 `add_plugins(..)` 收下 —— 0.20 里 `add_plugins` 要的是
//     `impl Plugins<M>`，而**元组和插件组都实现了它**（`bevy_app/src/plugin.rs` 里
//     的 `impl_plugins_tuples!` 给元组统一实现），所以元组写法少一层包装、效果等价。
//
// （与 016 唯一的行为差别在"插件注册的顺序"上，但 016 里 `PluginGroupBuilder` 也是
//   先 `ScorePlugin` 后 `EnemyPlugin`，两边一致，所以顺序相关的输出也一致。）
//
// ─────────────────────────────────────────────────────────────────────
// 目录结构就是这样长出来的
//
//   examples/017_module/
//     main.rs      只做组装：装插件 + 声明跨插件顺序
//     common.rs    跨模块共享的东西（组件、SystemSet）
//     score.rs     一个功能 = 一个文件 = 一个插件
//     enemy.rs     同上
//
// 三条约定值得照抄：
//
// 1. **一个功能一个文件**，文件里通常只有三样：专属资源 / 专属组件 / 那个插件。
// 2. **只 `pub` 出插件**（以及别的模块确实要用的类型）。系统函数保持私有 ——
//    上面 `report_score`、`check_arrival` 都没有 `pub`，因为只有本文件的插件用到它们。
//    这既是封装，也让"这个函数会被谁调用"一目了然。
// 3. **共享的东西才进 `common`**，别把什么都往里塞 —— 那会退化成新的"巨型 main"。
//
// ─────────────────────────────────────────────────────────────────────
// 提前避坑：模块和插件不是一回事
//
//   `mod` 是 **Rust 语言**的模块系统，管的是"代码放在哪个文件、谁能看见"
//   `Plugin` 是 **Bevy 框架**的组织方式，管的是"哪组系统/资源被注册进 App"
//
// 两者经常一一对应（一个模块里放一个插件），但**没有绑定关系**：
// 一个模块里可以放三个插件，一个插件也可以横跨多个模块。
// 本讲只是因为"往往正好对应"才这么摆。
//
// ─────────────────────────────────────────────────────────────────────
// 几个实际会用到的写法
//
//   `mod common;`        声明子模块 —— 文件就在同级目录的 `common.rs`
//   `use crate::common::GameSet;`   从 crate 根开始找（example 的 crate 根就是 main.rs）
//   `use super::Score;`   从父模块找
//   `pub(crate)`          只在本 crate 内可见，比 `pub` 更克制
//
// 当模块多起来，可以给每个模块建一个目录：`foo/mod.rs` 或 `foo.rs` + `foo/`。
// 另外常见一个 `prelude.rs`，把常用的类型 `pub use` 出来，
// 别处就能 `use crate::prelude::*;` 一行搞定 —— 本讲只有四个文件，还用不上。
//
// ─────────────────────────────────────────────────────────────────────
// 顺带一提：`src/main.rs` 是另一个 crate
//
// `examples/` 下的每个 example 都是**独立的 crate**，和 `src/main.rs` 互不相干 ——
// 所以这里 `use crate::common::..` 指的是**本 example 的** crate 根，
// 不是顶层 `src/`。两边无法直接共享代码（想共享得抽成 `src/lib.rs`，
// 或用 `#[path]` 之类的手段，超出本讲范围）。
